extern crate alloc;

// --- Core Modules (flaga_core) ---
// These modules define the fundamental data structures and logic.
pub use flaga_core::{
    enum_flag_counter,   // Enum-based bitmask logic
    error,               // The FlagError enum (liaise codes)
    flag_descriptor,     // The FlagDescriptor structs generated by macros
    flag_group,          // Logic for grouping multiple flags together
    flag_parser,         // The logic engine for string-based flag evaluation
    flag_type,           // The FlagType (Binary/Hex/Enum) discriminator
    flag,                // The core Flag trait definition
    module_flag,         // Positional bitset implementation (ModuleFlags)
    macros,              // Code generation tools
    macros_prelude,      // Path re-exports of the macros
    flag_types,          // The macro-generated BinaryFlag, HexFlag
    state,               // Pure persisted state
};

// --- Event Modules (flaga_events) ---
pub use flaga_events::{
    features,            // Feature-gate management
    flag_event_manager,  // Coordinator for triggered flag events
    flag_event,          // Individual event definitions
    flag_trigger,        // Functional wrappers for conditional execution
};

// --- Store Modules (flaga_store) ---
pub use flaga_store::{
    flag_manager_builder,// The Fluent Builder API for the manager
    flag_manager,        // The main thread-safe state coordinator
    flag_store,          // Persistence backends
};

pub mod prelude;             // Main API exports
pub use prelude::*;          // enable use of main API exports

// --- Macros ---
// The #[macro_export] macros live at the flaga_core root; re-export them so
// they stay reachable as `flaga::<macro>!`.
pub use flaga_core::{
    impl_flag_trait,
    impl_new_flag,
    impl_default,
    impl_from_flag,
    impl_flag_value,
    impl_descriptor,
};

// --- Re-exports ---
#[cfg(feature = "serde")]
pub use flaga_core::serde;
